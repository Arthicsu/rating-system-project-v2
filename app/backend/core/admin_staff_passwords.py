"""
Пароли сотрудников из админки одним CSV (admin action'ы Staff и User).

Учётки кафедр, деканатов и ректората общие, сами сотрудники пароль не меняют - им
управляет ОИ. Суперпользователь выбирает учётки, подтверждает и сразу скачивает CSV
с новыми паролями. В отличие от log_generated_passwords на сервере файл не хранится:
потеряли - запустите действие заново, старые пароли и сессии перестанут работать.
"""
import csv
import io
import logging

from django.contrib import messages
from django.contrib.admin import helpers
from django.db import transaction
from django.http import HttpResponse
from django.template.response import TemplateResponse
from django.utils import timezone
from django.views.decorators.debug import sensitive_variables

from university_structure.models import Staff

from .admin_password_generator import generate_password

audit_logger = logging.getLogger('audit')


# Пароли не попадут в отчёт об ошибке (страница DEBUG, письмо админам), если упадёт после коммита.
@sensitive_variables('password', 'buffer')
def generate_staff_passwords_csv(users, actor) -> str:
    """Новый пароль каждому из users; возвращает CSV «Логин;Подразделение;Пароль» (BOM - для Excel)."""
    buffer = io.StringIO()
    writer = csv.writer(buffer, delimiter=';')
    writer.writerow(['Логин', 'Подразделение', 'Пароль'])
    # Пароли меняются все или никакие: при сбое посередине часть учёток осталась бы
    # с паролями, которых нет ни в одном файле.
    with transaction.atomic():
        for user in users:
            password = generate_password()
            user.set_password(password)
            user.save(update_fields=['password'])
            writer.writerow([user.username, user.get_user_display_name(), password])
    audit_logger.info(
        "staff passwords regenerated by=%s count=%s ids=%s", actor.pk, len(users), [u.pk for u in users]
    )
    return '\ufeff' + buffer.getvalue()


def staff_passwords_action(modeladmin, request, users):
    """
    Общая часть action'ов: права, страница подтверждения, затем CSV.

    users - queryset User. В файл попадают только сотрудники; суперпользователи, учётки
    с доступом в админку (is_staff) и студенты - никогда, даже с профилем сотрудника:
    их пароли не должны оказаться в файле, который раздают по кафедрам.
    """
    # В админку пускает is_staff (по политике он только у суперпользователей ОИ), но
    # is_staff с правом просмотра списка увидел бы действие - а оно только для суперпользователя.
    if not request.user.is_superuser:
        modeladmin.message_user(
            request, "Генерировать пароли сотрудников может только суперпользователь.", messages.ERROR
        )
        return None
    selected_count = users.count()
    users = list(
        users.filter(
            staff_profile__isnull=False, student_profile__isnull=True, is_staff=False, is_superuser=False
        )
        .select_related('staff_profile__department', 'staff_profile__faculty')
        .order_by('username')
    )
    if not users:
        modeladmin.message_user(
            request,
            "Среди выбранных нет учёток сотрудников (суперпользователи, учётки с доступом в админку "
            "и студенты не в счёт) - пароли не менялись.",
            messages.WARNING,
        )
        return None
    if request.POST.get('post') != 'yes':
        if len(users) < selected_count:
            modeladmin.message_user(
                request,
                f"Пропущено учёток: {selected_count - len(users)} - студенты, суперпользователи "
                "и учётки с доступом в админку новых паролей не получают.",
                messages.WARNING,
            )
        return TemplateResponse(request, 'admin/staff_passwords_confirm.html', {
            **modeladmin.admin_site.each_context(request),
            'title': 'Сгенерировать новые пароли сотрудников?',
            'opts': modeladmin.model._meta,
            'users': users,
            # Подтверждается ровно показанный список: в форму уходят pk этих строк, а не
            # «выбрать все», иначе между двумя шагами список мог бы измениться.
            'selected': [u.staff_profile.pk if modeladmin.model is Staff else u.pk for u in users],
            'action_checkbox_name': helpers.ACTION_CHECKBOX_NAME,
        })

    filename = f"staff_passwords_{timezone.localtime():%Y-%m-%d_%H-%M-%S}.csv"
    response = HttpResponse(generate_staff_passwords_csv(users, request.user), content_type='text/csv; charset=utf-8')
    response['Content-Disposition'] = f'attachment; filename="{filename}"'
    # Браузер остаётся на странице подтверждения; сообщение придёт cookie вместе с файлом
    # и покажется на следующей странице админки - на списке, куда ведёт ссылка «Вернуться».
    modeladmin.message_user(
        request,
        f"Новые пароли сгенерированы, учёток: {len(users)}. Они только в файле {filename} - "
        "старые пароли и сессии этих учёток больше не действуют.",
        messages.SUCCESS,
    )
    return response
